// 元帳の明細1件の形（顧問先用アプリから移植）。
//
// CSVの読み取りは、この総合管理アプリに元からある解析（src/lib/keiei/ledger.ts）に
// 一本化した。取込の入口を2つ持つと、同じ元帳を2回取り込む羽目になり
// 税務チェックの会計監査ともデータがずれるため（利用者からの指摘で統一）。
// ここは「集計・名寄せが受け取る形」だけを定義する。

export interface LedgerEntry {
  /** 日付 YYYY-MM-DD */
  d: string;
  /** この明細が属する勘定科目のコード */
  ac: string;
  /** この明細が属する勘定科目名 */
  an: string;
  /** 相手科目名 */
  ca: string;
  /** 摘要（原文。空白を整えただけ） */
  no: string;
  /** 摘要から取り出した取引先の表記 */
  p: string;
  /** 借方金額 */
  dr: number;
  /** 貸方金額 */
  cr: number;
  /** 内部取引（資金移動・繰越）。取引先の集計から除く */
  x?: 1;
}
