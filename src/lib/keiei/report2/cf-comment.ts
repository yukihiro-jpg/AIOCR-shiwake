/**
 * 営業CF・投資CF・財務CF の符号から、社長向けのパターンコメントを返す。
 * 8通りすべてを網羅しているので、どんな入力でも必ず title/body が入った結果を返す
 * （データ不足で 0 が並んでも '＋＋＋' に落ちるだけで、例外は投げない）。
 */
export function cfPatternOf(op: number, inv: number, fin: number): CfPattern {
  const sign = cfSignKey(op, inv, fin)
  const p = PATTERNS[sign]
  // 8通りを網羅しているため通常ここには来ない（将来 signChar を増やしたときの保険）
  if (!p) return { sign, title: '—', body: '' }
  return { sign, title: p.title, body: p.body }
}

/**
 * 紙面（P3）の「3つのCFの組み合わせ（8通り）」の一覧表。並び順と「意味」欄の文言は
 * 確定済みデザインモックのとおり（モックが正）。ページ側は mark で該当行を強調する。
 */
export interface CfPatternRow {
  /** 表示記号（①〜⑧） */
  mark: string
  sign: string
  op: string
  inv: string
  fin: string
  /** 表の「意味」欄（1行に収まる短文） */
  meaning: string
}
