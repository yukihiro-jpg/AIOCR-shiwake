// 新報告書 v2 ── キャッシュ・フロー3区分（営業・投資・財務）のパターン判定コメント（P3）。
//
// 設計の意図（なぜこうしたか）:
// - CF計算書は「営業＋◯◯／投資△◯◯／財務＋◯◯」と数字を並べただけでは社長に伝わらない。
//   金額の大小ではなく **符号の組み合わせ（2×2×2＝8通り）** で会社の局面が決まるので、
//   8通りすべてに型名と本文を用意し、抜け（該当なしで無言になる）を作らない。
// - 判定は符号だけ。金額を混ぜた条件分岐（例「営業CFが返済額を下回ったら」）はここに入れない。
//   金額の評価は loan2.ts（返済カバー率）など専用の計算が持っており、二重に判定すると
//   紙面の中で言っていることが食い違うため。**金額は呼び出し側が文章に添える**。
// - 本文に数値・単位を書かない。ここは「型の説明」だけを持ち、リード文の組立て
//   （<b>営業 ＋19,200 ／ …</b> の部分）は pages 側が amt() で作る。
// - 0 は ＋ 扱い。会計データが0ちょうど（＝その区分の動きが無い）のとき「−」と読ませると
//   資金が出ていったように見えるため、「減っていない」側に寄せる。
// - 断定しすぎない書き方にそろえる。同じ符号でも背景（大型投資の前段か資金不安か）は
//   会社ごとに違うので、「何が起きているか → 何を確認すべきか」の順で確認を促す形にしている。
import type { CfPattern } from './types'

/** 符号の表示文字。全角プラス(U+FF0B)とマイナス記号(U+2212)＝モックの表と同じ字体 */
export const CF_PLUS = '＋'
export const CF_MINUS = '−'

/** 符号1文字（0 と NaN は ＋ 扱い） */
function signChar(n: number): string {
  return isFinite(n) && n < 0 ? CF_MINUS : CF_PLUS
}

/** 3区分の符号を並べた3文字キー（例 '＋−＋'） */
export function cfSignKey(op: number, inv: number, fin: number): string {
  return signChar(op) + signChar(inv) + signChar(fin)
}

